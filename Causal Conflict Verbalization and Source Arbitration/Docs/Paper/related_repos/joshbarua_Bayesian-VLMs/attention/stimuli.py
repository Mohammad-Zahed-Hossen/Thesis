def load_corpus(dataset_path: str | None):
    """Load the local pixel-normalized dataset or the hosted dataset."""
    from datasets import load_dataset, load_from_disk

    if dataset_path:
        return load_from_disk(dataset_path), dataset_path
    return (
        load_dataset(CONFLICTING_MODALITY_DATASET, cache_dir=HF_CACHE_DIR),
        CONFLICTING_MODALITY_DATASET,
    )


def build_example_index(datasets) -> list[tuple[str, int]]:
    """Map the repository-wide global id to ``(dataset, local index)``."""
    index: list[tuple[str, int]] = []
    for dataset in sorted(datasets):
        index.extend((dataset, local) for local in range(len(datasets[dataset])))
    return index


def load_splits(deg_run_id: str) -> dict[str, list[int]]:
    path = get_run_dir(deg_run_id) / "splits.json"
    info = json.loads(path.read_text())
    split = info.get("within_mixture")
    if split is None:
        raise KeyError(f"{path} has no 'within_mixture' split")
    return {
        name: [int(value) for value in values]
        for name, values in split.items()
        if isinstance(values, list)
    }


def stratified_sample(ids: Iterable[int], id_to_local: list[tuple[str, int]],
                      n: int | None, seed: int) -> list[int]:
    """Cap the pool while balancing the source datasets."""
    ids = sorted({int(value) for value in ids if int(value) < len(id_to_local)})
    if n is None or n >= len(ids):
        return ids
    by_dataset: dict[str, list[int]] = {}
    for idx in ids:
        by_dataset.setdefault(id_to_local[idx][0], []).append(idx)
    rng = random.Random(seed)
    for values in by_dataset.values():
        rng.shuffle(values)
    selected: list[int] = []
    datasets = sorted(by_dataset)
    while len(selected) < n and any(by_dataset[name] for name in datasets):
        for name in datasets:
            if by_dataset[name] and len(selected) < n:
                selected.append(by_dataset[name].pop())
    return sorted(selected)


def blur(image, sigma: float):
    return image if sigma == 0 else image.filter(ImageFilter.GaussianBlur(sigma))


class TextVariants:
    """Load the exact token-noise variants generated by Pipeline 1."""

    def __init__(self, grid: str, directory: Path = DEG_DIR):
        self.grid = grid
        self.directory = directory
        self.cache: dict[str, dict] = {}

    def _load(self, dataset: str) -> dict:
        if dataset not in self.cache:
            path = self.directory / f"token_noise_{self.grid}_{dataset}.json"
            if not path.exists():
                path = self.directory / f"token_noise_{dataset}.json"
            if not path.exists():
                raise FileNotFoundError(
                    f"no token-noise variants for {dataset} (grid={self.grid}); "
                    "run transitions/generate_text_degradations.py first"
                )
            self.cache[dataset] = json.loads(path.read_text())
        return self.cache[dataset]

    def passage(self, dataset: str, local_idx: int, level: int,
                original: str) -> str:
        if level == 0:
            return original
        variants = self._load(dataset).get(str(local_idx))
        if variants is None:
            raise KeyError(f"no variants for {dataset}/{local_idx}")
        if level - 1 >= len(variants):
            raise IndexError(f"{dataset}/{local_idx}: level {level} out of range")
        return variants[level - 1]


class StimulusBuilder:
    """Build the paper's canonical ``[image][passage question]`` prompt."""

    def __init__(self, adapter, variants: TextVariants):
        self.adapter = adapter
        self.variants = variants

    def skippable(self, example) -> bool:
        return answers_are_skippable(
            self.adapter.tokenizer,
            example["text_answer"],
            example["vision_answer"],
        )

    def build_cell(self, example, image, passage: str):
        return build_joint(
            self.adapter,
            image,
            passage,
            example["question"],
            example["text_answer"],
            example["vision_answer"],
            image_first=True,
        )
